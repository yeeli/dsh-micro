//   desc       一句话说明（卡片上的副标题：这个插件干什么用）
//   installed  安装状态 —— **手写**，不做任何运行时检测（用户 2026-09-26 明确要求
//              「不用去检测系统了」）。卡片右侧的「已安装 / 未安装」徽标就照它渲染。
//              不写 = 未安装。
//   usedBy     （可选）依赖它的按键功能 —— 动作 id 数组（见 actions/registry.js 总表），
