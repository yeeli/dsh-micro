export const PLUGIN_DEPS = []

// ---------------------------------------------------------------------------
// ④ 摇杆四个方向的出厂功能（用户 2026-09-26 要求收进这里）
// ---------------------------------------------------------------------------
// 摇杆是设备底部那个模拟摇杆：宿主把它归一化成**四个方向**（见 src/core/joystick.js 的角度约定
// 0=右 / 90=下 / 180=左 / 270=上），每推到一个新方向就报一次。方向 → 干什么，由**设置页**决定
// （`joystick` 字段：`{ up, right, down, left }` → 动作名，存的是**动作名本身**）。
//
// 这一节回答的就是「用户没改过时，四个方向各干什么」。
//
//   JOY_ACTION    取值域：已接线的动作名（设置页下拉里能选的那些；值就是存储值，也是执行时认的词）
//   JOY_DEFAULTS  出厂映射：方向 → 动作名（下面这张表）
//
// 方向键名用的是宿主 schema / 存档里的那四个（`up` `right` `down` `left`，别改成 top/bottom ——
// 改了等于把所有人的老设置作废），括号里是设备上的方位：
//
//   up    （上）→ 切换规划模式   推上去开/关规划模式
//   right （右）→ 重做           应用里重做被撤销的那次编辑
//   down  （下）→ 切换侧边栏     打开/收起侧边栏
//   left  （左）→ 撤销           应用里撤销上一次编辑
//
// 为什么要「撤销 / 重做」这两个词（而不是「返回 / 前进」）：用户要的是**在应用里**操作 undo/redo，
// 老名字只有描述里才提到撤销，看设置页根本认不出这就是 undo。
//
// 老存档里的「返回 / 前进」仍然认（`JOY_LEGACY`，在 client/joystick.js）——
// 升级不能把用户存过的设置废掉。
//
// 改出厂功能：把 `JOY_DEFAULTS` 里对应方向的值换成**别的动作名**（必须是 `JOY_ACTION` 里的
// 某个值，或 `'none'` = 该方向不绑定）。想加一个**新的**可选动作：在 `JOY_ACTION` 里加一个键，
// 并在设置页的候选清单（components/modals/joystick.jsx 的 JOY_ACTIONS）里加一条 ——
// 两处都加才「选得到」；能不能**执行**则取决于 client/joystick.js 的 `run()` 有没有接线。

