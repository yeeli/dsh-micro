// ---------------------------------------------------------------------------
// ② 布局出厂按键功能 —— 每颗键（用户没改过时）按下执行什么
// ---------------------------------------------------------------------------
// **键 = 设备键码**（ACT06..ACT12，设备上报的动作键码），**值 = 功能名** —— 也就是
// actions/registry.js 那张功能总表里某条记录的 `id`（'archive' / 'voice' / …）。
// 用户没改过某颗键时（actLabels 里没有这条），就按这里执行；判据只有一处：
// utils/keycaps.js 的 capFor()（渲染与动作解析共用它）。
//
// ⚠ 值**不是键码、也不是键帽 id**，必须是功能名 —— 曾写成 `ACT06: 'ACT06'` 那种自己指向自己的
// 形式，光看值读不出「这颗键出厂干什么」。现在值就是功能名，一行一个功能，一眼可读：
//
//   ACT06  'mode'     切换 Agent 模式（模式）—— 在 Agent 预设之间循环
//                     ⚠ 2026-09-28 之前这里写的是 'none'（「保留」），值被人手改成了 'fork'
//                     而注释没跟着走（一处漂移）。本轮按用户要求改名并定死为 'mode'：
//                     **存储 id 仍是 ACT06**，所以老存档一个字都不用改。
//   ACT07  'archive'  归档当前会话（归档）
//   ACT08  'reject'   拒绝当前待确认的交互（拒绝）
//   ACT09  'approve'  批准当前待确认的交互（批准）
//   ACT10  'voice'    语音输入：按住说话（语音）
//   ACT11  'voice'    同上 —— 合并态下它与 ACT10 是**同一颗两倍宽 Mic 键**的两个开关，
//                     出厂功能当然一样（拆分态不走这张表，见下面的设备事实）
//   ACT12  'send'     发送当前输入（发送）
//
// 2026-09-28 起**「预留/保留」不再是出厂选项**：`none` 那条功能仍在总表里（旋钮下拉的「无」），
// 但摘掉了 capId —— 当不了键帽，也就不该出现在这张表里（自检 verify_keycaps 会拦）。
//
// 要换某颗键的出厂功能：把值改成**目标功能名**（例如把 ACT07 改成 `'fork'` = 出厂就分叉会话）。
// ⚠ 只认总表里**带 capId** 的那些功能（keycapActions()，也就是「编辑按键」弹窗里能选的那些）——
// 写成别的名字（比如只属于旋钮的 `'scroll_up'`）等于那颗键出厂没功能，自检 verify_keycaps 会红。
// 可用的名字在这里现查：`__dshOmkb.actions.keycaps()`（浏览器控制台）或在
// actions/registry.js 里搜 `capId:`。
//
// 键帽（界面上画什么图标）**由功能名派生**，不必也不该在这里写第二遍：utils/keycaps.js 拿总表的
// `capId` 把功能名翻成键帽 id（'voice' → 'ACT10'，因为 MIC 那颗键帽的 id 沿用设备键码）。
// 于是「改功能」是一处改、界面自动跟着对，不会出现「表里改了、键上还是老图标」。
//
// 设备事实（Codex Micro 官方文档）：底部那颗**两倍宽的 Mic 键下面有两个开关**，分别上报
// ACT10 / ACT11，官方说「可以对两个开关独立映射」：
//   * micKey=false（默认，合并态）：两个开关当**一颗宽键**用 —— 出厂功能都是 'voice'。
//   * micKey=true（拆分态）：两个开关各自独立 —— 左开关（ACT10）出厂仍是 'voice'（MIC），
//     右开关（ACT11）出厂是**自定义键**（未指派 = 按下什么都不做，用户点它选键帽）。
//     为什么右边留空：拆开之后两颗都印着 MIC 没有意义（按下去本来就一样），
//     留一颗给用户自己指派才有意义。这一条由 `MIC_CUSTOM_CODE`（在 utils/keycaps.js）实现，不写在这里。

export const FACTORY_KEY_FUNCS = {
  ACT06: 'mode',
  ACT07: 'archive',
  ACT08: 'reject',
  ACT09: 'approve',
  ACT10: 'voice',
  ACT11: 'voice',
  ACT12: 'send'
}

